function normalize(str: string): string {
  return str
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "") // remove accents
    .replace(/[^a-z0-9\s/]/g, "")
    .trim();
}

export function findInLocalDatabase(metier: string): AnalysisResult | null {
  const query = normalize(metier);
  if (!query) return null;

  // 1. Exact match
  if (JOB_DATABASE[query]) return JOB_DATABASE[query];

  // 2. Check if any key is contained in the query OR query is contained in the key
  for (const [key, result] of Object.entries(JOB_DATABASE)) {
    const normKey = normalize(key);
    if (query.includes(normKey) || normKey.includes(query)) {
      return result;
    }
  }

  // 3. Word overlap: check if any significant word matches
  const queryWords = query.split(/\s+/).filter((w) => w.length > 3);
  for (const [key, result] of Object.entries(JOB_DATABASE)) {
    const keyWords = normalize(key).split(/\s+/).filter((w) => w.length > 3);
    const overlap = queryWords.filter((w) => keyWords.includes(w));
    if (overlap.length > 0) return result;
  }

  return null;
}

/** Returns the 3 closest job names from the database (for suggestions) */
export function getSimilarJobs(metier: string, count = 3): string[] {
  const query = normalize(metier);
  const queryWords = query.split(/\s+/).filter((w) => w.length > 2);

  const scored = Object.entries(JOB_DATABASE).map(([key]) => {
    const normKey = normalize(key);
    const keyWords = normKey.split(/\s+/).filter((w) => w.length > 2);
    let score = 0;
    queryWords.forEach((w) => { if (normKey.includes(w)) score += 2; });
    keyWords.forEach((w) => { if (query.includes(w)) score += 1; });
    return { label: JOB_DATABASE[key].metier, score };
  });

  return scored
    .sort((a, b) => b.score - a.score)
    .slice(0, count)
    .map((s) => s.label);
}

